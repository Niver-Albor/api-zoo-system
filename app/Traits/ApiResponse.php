<?php

namespace App\Traits;

trait ApiResponse
{
    public function successResponse($data, $message = 'Operación existosa', $code = 200)
    {
        return response()->json([
            'success' => true,
            'message' => $message,
            'data' => $data
        ], $code);
    }

    public function errorResponse($message = 'Ocurrió un error', $code = 400)
    {
        return response()->json([
            'success' => false,
            'message' => $message,
            'data' => null
        ], $code);
    }
}
